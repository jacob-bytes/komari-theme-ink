/**
 * 查询地区代码对应的地理坐标。找不到时返回 null，由调用方决定如何处理
 * （例如跳过该地区的标记渲染，而不是画在默认位置误导用户）。
 */
export function getRegionCoordinate(code: string | null | undefined): [number, number] | null {
  if (!code)
    return null
  const coord = REGION_COORDINATES[code.toUpperCase()]
  return coord ?? null
}
